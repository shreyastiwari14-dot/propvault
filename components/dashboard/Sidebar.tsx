export function Sidebar() {
  const pathname = usePathname()

  async function handleSignOut() {
    const supabase = createClient()
    await supabase.auth.signOut()
    window.location.href = '/login'
  }

  return (
    <div className="w-56 bg-white border-r border-[#E5E3DE] flex flex-col h-full fixed left-0 top-0 z-30">
      {/* Logo */}
      <div className="p-5 border-b border-[#E5E3DE]">
        <div className="flex items-center gap-2">
          <div className="w-7 h-7 bg-[#D4501A] rounded-md flex items-center justify-center flex-shrink-0">
            <span className="text-white font-bold text-xs">P</span>
          </div>
          <span className="font-bold text-[#111110] tracking-tight">PropVault</span>
        </div>
      </div>

      {/* Nav */}
      <nav className="flex-1 p-3 space-y-0.5 overflow-y-auto">
        {navItems.map((item) => {
          const active = item.exact
            ? pathname === item.href
            : pathname.startsWith(item.href)

          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 px-3 py-2 rounded-lg text-sm font-medium transition-colors ${
                active
                  ? 'bg-[#FEF0EA] text-[#D4501A]'
                  : 'text-[#8A8A84] hover:text-[#111110] hover:bg-[#F7F6F3]'
              }`}
            >
              <span className={active ? 'text-[#D4501A]' : 'text-[#8A8A84]'}>
                {item.icon}
              </span>
              {item.label}
            </Link>
          )
        })}
      </nav>

      {/* Sign out */}
      <div className="p-3 border-t border-[#E5E3DE]">
        <button
          onClick={handleSignOut}
          className="w-full flex items-center gap-3 px-3 py-2 rounded-lg text-sm font-medium text-[#8A8A84] hover:text-[#111110] hover:bg-[#F7F6F3] transition-colors"
        >
          <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
          </svg>
          Sign Out
        </button>
      </div>
    </div>
  )
}
